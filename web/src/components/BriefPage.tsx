import { useEffect, useMemo, useRef, useState } from "react";
import { Link, useParams, useSearchParams } from "react-router-dom";
import { CATEGORY_LABELS, LIVE_API_URL, citationLabel, disciplineOf, loadBundle, longDate, shortDate } from "../lib";
import { useReview, type Decision } from "../review";
import type { BriefItem, Bundle, Index, Note } from "../types";
import AgentReplay from "./AgentReplay";
import AnswerKeyView from "./AnswerKeyView";
import ChartView from "./ChartView";
import EvidencePane from "./EvidencePane";
import LiveRunDialog from "./LiveRunDialog";
import WindowStrip from "./WindowStrip";
import { SeverityTag } from "./charts";

const STEPS = ["chart", "agent", "brief", "key"] as const;
type Step = (typeof STEPS)[number];

interface Selection {
  item: number | null;
  cite: string;
}

export default function BriefPage({ index }: { index: Index }) {
  const { id = "" } = useParams();
  const [bundle, setBundle] = useState<Bundle | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [liveAt, setLiveAt] = useState<string | null>(null);
  const [selection, setSelection] = useState<Selection | null>(null);
  const [showLive, setShowLive] = useState(false);
  const [params, setParams] = useSearchParams();
  const step: Step = (STEPS as readonly string[]).includes(params.get("step") ?? "") ? (params.get("step") as Step) : "chart";
  const panelRef = useRef<HTMLDivElement>(null);
  const goTo = (next: Step, scroll = false) => {
    setParams(next === "chart" ? {} : { step: next }, { replace: true });
    setSelection(null);
    if (scroll) requestAnimationFrame(() => panelRef.current?.scrollIntoView({ behavior: "smooth", block: "start" }));
  };

  useEffect(() => {
    setBundle(null);
    setError(null);
    setLiveAt(null);
    setSelection(null);
    loadBundle(id).then(setBundle, (e: Error) => setError(e.message));
  }, [id]);

  const briefKey = liveAt ? `${id}:live:${liveAt}` : `${id}:${index.generated_at}`;
  const review = useReview(briefKey);
  const notes = useMemo(() => new Map<string, Note>((bundle?.notes ?? []).map((n) => [n.id, n])), [bundle]);

  if (error) return <p className="notice">{error} <Link to="/">Back to the review queue</Link></p>;
  if (!bundle) return <p className="loading">Loading the brief</p>;

  const { brief, participant: p } = bundle;
  const cited = new Set(brief.items.flatMap((i) => i.citations));
  const decided = brief.items.filter((_, i) => review.state.decisions[i]).length;
  const allDecided = decided === brief.items.length;
  const selectedItem = selection?.item != null ? brief.items[selection.item] : null;
  const citedBy = selection ? brief.items.filter((i) => i.citations.includes(selection.cite)) : [];

  const select = (cite: string, item: number | null) =>
    setSelection((s) => (s?.cite === cite && s.item === item ? null : { cite, item }));

  return (
    <div className="page brief-page">
      <nav className="crumbs" aria-label="Breadcrumb">
        <Link to="/">Review queue</Link>
        <span aria-hidden="true">/</span>
        <span aria-current="page">{p.first_name} {p.last_name}</span>
      </nav>

      <header className="patient-head">
        <div className="patient-id">
          <h1>{p.first_name} {p.last_name}</h1>
          <dl className="patient-facts">
            <div><dt>Age</dt><dd>{p.age}</dd></div>
            <div><dt>Sex</dt><dd>{p.sex === "F" ? "Female" : "Male"}</dd></div>
            <div><dt>Lives in</dt><dd>{p.city}</dd></div>
            <div><dt>Enrolled</dt><dd>{longDate(p.enrollment_date)}</dd></div>
            <div><dt>Review window</dt><dd>{shortDate(p.window_start)} to {longDate(p.review_date)}</dd></div>
          </dl>
          {brief.run.sample && <p className="patient-flag">Sample brief built from the test answer key, not generated by Claude.</p>}
          {liveAt && <p className="patient-flag is-live" role="status">This brief was just generated live by Claude. Your review starts fresh.</p>}
        </div>
        <div className="patient-side">
          <p className="patient-sev" aria-label="Lines in this brief by severity">
            {(["high", "medium", "low"] as const).map((sv) => {
              const n = brief.items.filter((i) => i.severity === sv).length;
              return n ? <SeverityTag key={sv} severity={sv} count={n} /> : null;
            })}
            {brief.items.length === 0 && <span>No changes flagged</span>}
          </p>
          <div className="brief-tools">
            {LIVE_API_URL && (
              <button type="button" className="button" onClick={() => setShowLive(true)}>Watch the agent build one live</button>
            )}
            <button type="button" className="button-quiet" onClick={() => window.print()}>Export PDF</button>
          </div>
        </div>
      </header>

      <StoryNav bundle={bundle} step={step} onSelect={(st) => goTo(st)} />

      <div ref={panelRef} role="tabpanel" id={`panel-${step}`} aria-labelledby={`tab-${step}`} className="story-panel">
        {step === "chart" && (
          <>
            <ChartView bundle={bundle} cited={cited} />
            <p className="step-next">
              <button type="button" className="button" onClick={() => goTo("agent", true)}>Next: see what the agent did</button>
            </p>
          </>
        )}
        {step === "agent" && (
          <>
            <AgentReplay bundle={bundle} />
            <p className="step-next">
              <button type="button" className="button" onClick={() => goTo("brief", true)}>Next: read the brief it wrote</button>
            </p>
          </>
        )}
        {step === "key" && <AnswerKeyView bundle={bundle} evaluation={index.evaluation} />}
        {step === "brief" && (
          <>
      <WindowStrip windowStart={p.window_start} reviewDate={p.review_date} notes={bundle.notes} cited={cited}
                   selectedNote={selection?.cite ?? null} onSelect={(nid) => select(nid, null)} />

      <div className="brief-grid">
        <div className="brief-main">
          <section className="headline" aria-labelledby="headline-label">
            <p id="headline-label" className="headline-label">Headline</p>
            <p>{brief.headline}</p>
          </section>

          <section aria-labelledby="items-heading">
            <h2 id="items-heading" className="section-title">For the team to discuss</h2>
            {brief.items.length === 0 && <p>No changes needing discussion were found since the last review.</p>}
            <ol className="items">
              {brief.items.map((item, i) => (
                <ItemRow key={i} item={item} index={i} notes={notes} decision={review.state.decisions[i]}
                         selectedCite={selection?.item === i ? selection.cite : null}
                         onCite={(c) => select(c, i)}
                         onDecide={(d) => review.decide(i, d, CATEGORY_LABELS[item.category] ?? item.category)}
                         onUndo={() => review.undo(i, CATEGORY_LABELS[item.category] ?? item.category)} />
              ))}
            </ol>
          </section>

          <section className="approve-bar" aria-live="polite">
            {review.state.approvedAt ? (
              <p>
                <strong>Brief approved</strong> on {new Date(review.state.approvedAt).toLocaleString()}. Export it as a PDF
                for the meeting packet.
              </p>
            ) : (
              <p>{decided} of {brief.items.length} items reviewed. Approve, edit, or reject each line, then approve the brief.</p>
            )}
            {!review.state.approvedAt && (
              <button type="button" className="button" disabled={!allDecided} onClick={review.approveBrief}>
                Approve brief
              </button>
            )}
          </section>

          {brief.questions_for_team.length > 0 && (
            <section aria-labelledby="questions-heading">
              <h2 id="questions-heading" className="section-title">Questions for the team</h2>
              <ul className="questions">{brief.questions_for_team.map((q) => <li key={q}>{q}</li>)}</ul>
            </section>
          )}

          {brief.removed_claims.length > 0 && (
            <details className="removed">
              <summary>{brief.removed_claims.length} claim{brief.removed_claims.length > 1 ? "s" : ""} removed by the verifier</summary>
              <p>These lines were drafted but could not be supported by their sources, so they never reached the team.</p>
              <ul>{brief.removed_claims.map((c, i) => <li key={i}>{c.statement} <em>{c.verifier_note}</em></li>)}</ul>
            </details>
          )}

          <p className="step-next">
            <button type="button" className="button" onClick={() => goTo("key", true)}>
              Next: check it against the answer key
            </button>
          </p>
        </div>

        <aside className={`evidence${selection ? " is-open" : ""}`} aria-label="Evidence">
          <EvidencePane bundle={bundle} notes={notes} cite={selection?.cite ?? null} claim={selectedItem}
                        citedBy={citedBy} onClose={() => setSelection(null)} />
          <AuditLog events={review.state.events} />
        </aside>
      </div>

          </>
        )}
      </div>

      <PrintVersion bundle={bundle} decisions={review.state.decisions} approvedAt={review.state.approvedAt} />

      {showLive && (
        <LiveRunDialog participantId={p.id} name={p.first_name} onClose={() => setShowLive(false)}
                       onDone={(b) => {
                         setBundle(b);
                         setLiveAt(new Date().toISOString());
                         setSelection(null);
                         setShowLive(false);
                         goTo("brief");
                       }} />
      )}
    </div>
  );
}

// ---------------------------------------------------------------- the four steps

function StoryNav({ bundle, step, onSelect }: { bundle: Bundle; step: Step; onSelect: (s: Step) => void }) {
  const { brief, participant: p, answer_key: key } = bundle;
  const run = brief.run;
  const recordCount = 4;
  const caught = key ? key.must_surface.filter((t) => t.caught_by.length).length : 0;
  const steps: { id: Step; title: string; fact: string }[] = [
    { id: "chart", title: "The chart",
      fact: `${bundle.notes.length} notes and ${recordCount} records, ${shortDate(p.window_start)} to ${shortDate(p.review_date)}` },
    { id: "agent", title: "What the agent did",
      fact: run.sample ? "Sample brief, no agent run"
        : `${(run.tool_calls?.length ?? 0) + 1} chart lookups in ${Math.round(run.seconds ?? 0)} seconds for $${(run.cost_usd ?? 0).toFixed(2)}` },
    { id: "brief", title: "The brief",
      fact: `${brief.items.length} line${brief.items.length === 1 ? "" : "s"} for the team, each linked to its source` },
    { id: "key", title: "Checked against the answer key",
      fact: key ? `Caught ${caught} of ${key.must_surface.length} planted events` : "No answer key" },
  ];
  const onKey = (e: React.KeyboardEvent, i: number) => {
    const d = e.key === "ArrowRight" ? 1 : e.key === "ArrowLeft" ? -1 : 0;
    if (!d) return;
    e.preventDefault();
    const next = steps[(i + d + steps.length) % steps.length].id;
    onSelect(next);
    document.getElementById(`tab-${next}`)?.focus();
  };
  return (
    <div className="story" role="tablist" aria-label="How this brief came together">
      {steps.map((s, i) => (
        <button key={s.id} id={`tab-${s.id}`} type="button" role="tab" aria-selected={step === s.id}
                aria-controls={`panel-${s.id}`} tabIndex={step === s.id ? 0 : -1}
                className={`story-step${step === s.id ? " is-current" : ""}`}
                onClick={() => onSelect(s.id)} onKeyDown={(e) => onKey(e, i)}>
          <span className="story-num" aria-hidden="true">{i + 1}</span>
          <span className="story-title">{s.title}</span>
          <span className="story-fact">{s.fact}</span>
        </button>
      ))}
    </div>
  );
}

// ---------------------------------------------------------------- one line of the brief

interface ItemProps {
  item: BriefItem;
  index: number;
  notes: Map<string, Note>;
  decision?: Decision;
  selectedCite: string | null;
  onCite: (cite: string) => void;
  onDecide: (d: Decision) => void;
  onUndo: () => void;
}

function ItemRow({ item, index, notes, decision, selectedCite, onCite, onDecide, onUndo }: ItemProps) {
  const [mode, setMode] = useState<"view" | "edit" | "reject">("view");
  const [draft, setDraft] = useState(item.statement);
  const [reason, setReason] = useState("");
  const text = decision?.status === "edited" ? decision.text : item.statement;

  return (
    <li className={`item sev-border-${item.severity}${decision ? ` is-${decision.status}` : ""}`}>
      <p className="item-kicker">
        <span className={`sev sev-${item.severity}`}>{item.severity}</span>
        <span className="item-category">{CATEGORY_LABELS[item.category] ?? item.category}</span>
        {item.verdict === "partially_supported" && <span className="partial">Partly supported, check before approving</span>}
      </p>

      {mode === "edit" ? (
        <form className="item-form" onSubmit={(e) => { e.preventDefault(); onDecide({ status: "edited", text: draft.trim() }); setMode("view"); }}>
          <label htmlFor={`edit-${index}`} className="visually-hidden">Edit this line</label>
          <textarea id={`edit-${index}`} value={draft} rows={3} onChange={(e) => setDraft(e.target.value)} />
          <div className="item-actions">
            <button type="submit" className="button-small" disabled={!draft.trim()}>Save edit</button>
            <button type="button" className="link-button" onClick={() => { setDraft(text); setMode("view"); }}>Cancel</button>
          </div>
        </form>
      ) : (
        <p className="item-text">
          {decision?.status === "rejected" ? <s>{text}</s> : text}
        </p>
      )}

      {item.verdict === "partially_supported" && item.verifier_note && <p className="verifier-note">Verifier: {item.verifier_note}</p>}

      <p className="cites">
        <span className="visually-hidden">Sources:</span>
        {item.citations.map((c) => {
          const note = notes.get(c);
          const d = note ? disciplineOf(note.author_role) : "record";
          return (
            <button key={c} type="button" className={`cite${selectedCite === c ? " is-active" : ""}`}
                    aria-pressed={selectedCite === c} onClick={() => onCite(c)}>
              <span className={`swatch d-${d}`} aria-hidden="true" />
              {citationLabel(c, notes)}
            </button>
          );
        })}
      </p>

      {mode === "reject" ? (
        <form className="item-form" onSubmit={(e) => { e.preventDefault(); onDecide({ status: "rejected", reason: reason.trim() }); setMode("view"); }}>
          <label htmlFor={`reason-${index}`}>Why reject this line? (optional)</label>
          <input id={`reason-${index}`} value={reason} onChange={(e) => setReason(e.target.value)} />
          <div className="item-actions">
            <button type="submit" className="button-small button-danger">Reject line</button>
            <button type="button" className="link-button" onClick={() => setMode("view")}>Cancel</button>
          </div>
        </form>
      ) : mode === "view" && (
        <div className="item-actions">
          {decision ? (
            <>
              <span className={`decision decision-${decision.status}`}>
                {decision.status === "approved" ? "Approved" : decision.status === "edited" ? "Edited and approved" : "Rejected"}
                {decision.status === "rejected" && decision.reason ? `: ${decision.reason}` : ""}
              </span>
              <button type="button" className="link-button" onClick={onUndo}>Undo</button>
            </>
          ) : (
            <>
              <button type="button" className="button-small" onClick={() => onDecide({ status: "approved" })}>Approve</button>
              <button type="button" className="link-button" onClick={() => { setDraft(text); setMode("edit"); }}>Edit</button>
              <button type="button" className="link-button" onClick={() => setMode("reject")}>Reject</button>
            </>
          )}
        </div>
      )}
    </li>
  );
}

// ---------------------------------------------------------------- supporting panels

function AuditLog({ events }: { events: { at: string; action: string; detail?: string }[] }) {
  return (
    <section className="audit" aria-labelledby="audit-heading">
      <h2 id="audit-heading">Review log</h2>
      {events.length === 0 ? (
        <p>Every approval, edit, and rejection is recorded here with its time.</p>
      ) : (
        <ol>
          {events.map((e, i) => (
            <li key={i}>
              <time dateTime={e.at}>{new Date(e.at).toLocaleTimeString([], { hour: "numeric", minute: "2-digit" })}</time>
              <span>{e.action}{e.detail ? `: ${e.detail}` : ""}</span>
            </li>
          ))}
        </ol>
      )}
      <p className="audit-note">In this demo the log is kept in your browser.</p>
    </section>
  );
}

function PrintVersion({ bundle, decisions, approvedAt }: { bundle: Bundle; decisions: Record<number, Decision>; approvedAt: string | null }) {
  const { brief, participant: p } = bundle;
  return (
    <section className="print-only" aria-hidden="true">
      <h1>IDT brief: {p.first_name} {p.last_name}</h1>
      <p>Review {longDate(p.review_date)}. Covers {longDate(p.window_start)} onward. Synthetic data.</p>
      <p><strong>{brief.headline}</strong></p>
      <ol>
        {brief.items.map((item, i) => {
          const d = decisions[i];
          if (d?.status === "rejected") return null;
          return (
            <li key={i}>
              [{item.severity}] {CATEGORY_LABELS[item.category] ?? item.category}: {d?.status === "edited" ? d.text : item.statement}
              {d?.status === "edited" && " (edited by reviewer)"}
              {!d && " (not yet reviewed)"}
            </li>
          );
        })}
      </ol>
      {brief.questions_for_team.length > 0 && (
        <>
          <h2>Questions for the team</h2>
          <ul>{brief.questions_for_team.map((q) => <li key={q}>{q}</li>)}</ul>
        </>
      )}
      <p>{approvedAt ? `Approved ${new Date(approvedAt).toLocaleString()}.` : "Not yet approved."} Prepared with IDT Prep.</p>
    </section>
  );
}
